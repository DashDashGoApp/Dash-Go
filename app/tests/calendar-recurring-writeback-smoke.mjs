import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {resolve} from "node:path";
const root=resolve(process.argv[2]||".");
const read=rel=>readFileSync(resolve(root,rel),"utf8");
const actions=read("ui/js/calendar-writeback.js");
const form=read("ui/js/calendar-event-form.js");
const eventCache=read("internal/calendar/events/cache.go")+read("internal/calendar/events/serialize.go");
const writer=read("internal/calendar/icalwrite/recurrence_write.go");
const items=read("internal/calendar/writeback/items.go");
const routesPublic=read("cmd/dashboard-control-server/http_routes_public_post.go");
const routesControl=read("cmd/dashboard-control-server/http_routes_post_calendar.go");
const server=read("cmd/dashboard-control-server/calendar_writeback.go");
assert.match(actions,/Manage recurring event/,'recurring events need an explicit management entrypoint');
assert.match(actions,/Edit this occurrence/,'recurring manager must offer an occurrence scope');
assert.match(actions,/Edit entire series/,'simple recurring manager must offer a series scope');
assert.match(actions,/advanced repeat pattern/,'unsupported recurrence needs an explanatory provider-managed path');
assert.match(form,/scope==="occurrence"/,'event form must preserve occurrence scope');
assert.match(form,/\/api\/calendar\/event\/occurrence\/update/,'event form must use occurrence update route');
assert.match(form,/\/api\/calendar\/event\/series\/update/,'event form must use series update route');
assert.match(form,/repeat rule stays unchanged/,'series editor must not imply arbitrary RRULE editing');
assert.match(form,/This series has skipped dates/,'series date changes must warn when exclusions exist');
assert.match(eventCache,/canOccurrenceEdit/,'cache must identify a safe per-occurrence edit path');
assert.match(eventCache,/canSeriesEdit/,'cache must identify a narrow series edit path');
assert.match(eventCache,/occurrenceMs/,'cache must retain canonical occurrence identity');
assert.match(writer,/ApplyOccurrenceEdit/,'writer needs a detached occurrence mutation path');
assert.match(writer,/RECURRENCE-ID/,'occurrence mutation must write canonical recurrence identity');
assert.match(writer,/ApplySeriesEdit/,'writer needs a constrained master edit path');
assert.match(writer,/SeriesEditable/,'advanced recurrence patterns must remain provider-managed');
assert.match(writer,/componentSequence/,'new detached overrides must inherit a safe master sequence');
assert.match(items,/OccurrenceHasOverride/,'skip must refuse an occurrence that already has a detached override');
assert.match(items,/calendar event identifier is ambiguous/,'duplicate UID files must fail closed');
assert.match(routesPublic,/occurrence\/update[\s\S]*?calendarWritebackRequirePIN/,'recurrence writes retain the existing token policy');
assert.match(routesControl,/series\/update/,'token-gated calendar routes must recognize series updates');
assert.match(server,/calendarWritebackCacheCapability[\s\S]*?canOccurrenceEdit/,'server must reject stale or crafted occurrence targets');
assert.match(server,/canSkip/,'skip must validate a real cached occurrence too');
console.log("calendar recurring writeback smoke: explicit scopes, constrained recurrence mutation, and fail-closed server identity checks hold");
