#!/usr/bin/env node
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
const root=process.argv[2]||path.resolve(path.dirname(new URL(import.meta.url).pathname),"..");
const read=rel=>fs.readFileSync(path.join(root,rel),"utf8");
const js=["ui/js/weather-sources.js","ui/js/weather-blend.js","ui/js/weather-icons.js"].map(read).join("\n");
const go=["internal/weather/weather_keyed_providers.go","internal/weather/weather_keyed_accuweather.go","internal/weather/weather_keyed_normalize.go","internal/weather/weather_units.go"].map(read).join("\n");
const nws=read("internal/weather/weather_keyed_nws.go");
const om=read("internal/weather/weather_openmeteo.go");
const blend=read("internal/weather/weather_blend_go.go");
assert.match(js,/const WEATHER_PRECIP_MM_MAX=1500/);
assert.match(js,/fetch\("\/api\/weather"/,"browser Weather must consume the same-origin canonical aggregate");
assert.match(go,/_canonicalUnits.*"precipitation": "mm"/s,
  "server-owned Weather payloads must declare canonical millimetres");
assert.match(go,/totalprecip_mm/);
assert.doesNotMatch(go,/totalprecip_in/);
assert.match(go,/precipitationSumMMGo\(x\["rain"\], x\["snow"\]\)/);
assert.match(js,/function wxPrecipTotalText\(v\)/);
assert.match(js,/st\.networkCalls/,'source review must expose provider call counts');
assert.match(js,/st\.responseBytes/,'source review must expose provider response sizes');
assert.match(js,/st\.httpStatus/,'source review must expose provider HTTP status');
assert.match(js,/mm\/25\.4/,'imperial display must convert canonical millimetres to inches');
assert.match(js,/" mm total"/,'metric display must label canonical millimetres');
assert.match(js,/function blendPrecipitationTotal/,'precipitation needs its own robust blend');
assert.match(go,/precipitationMMGo\(day\["totalprecip_mm"\], "mm"\)/);
assert.match(go,/maxProbabilityGo\(day\["daily_chance_of_rain"\], day\["daily_chance_of_snow"\]\)/);
assert.match(go,/precipitationSumMMGo\(x\["rain"\], x\["snow"\]\)/);
assert.match(go,/googlePrecipitationMMGo/);
assert.match(go,/pirateHourlyLiquidTotalsGo/,'Pirate Weather must derive daily liquid-water equivalent from hourly intensity');
assert.match(go,/time\.LoadLocation\(zoneName\)/,'Pirate Weather totals must group by the provider timezone when available');
assert.match(go,/offsetHours \* float64\(time\.Hour\)/,'Pirate Weather offset fallback must treat offset as hours');
assert.doesNotMatch(go,/precipitationMMGo\(x\["precipAccumulation"\]/,'mixed physical Pirate Weather accumulation must not be treated as liquid-water equivalent');
assert.match(go,/visualCrossingWindUnitGo/,'Visual Crossing metric wind must be interpreted as kilometres per hour');
assert.match(nws,/precipitationMMGo\(x\["precipIN"\], "in"\)/);
assert.match(om,/q\.Set\("precipitation_unit", "mm"\)/);
assert.match(blend,/browser-authoritative normalized sources/);
assert.doesNotMatch(blend,/func blendCurrentGo/);
console.log("PASS: weather precipitation is canonical mm, display conversion is explicit, and provider multipliers are guarded");
