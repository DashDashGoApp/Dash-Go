#!/usr/bin/env node
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import {fileURLToPath} from "node:url";

const appRoot=path.resolve(path.dirname(fileURLToPath(import.meta.url)),"..");
const repoRoot=path.resolve(appRoot,"..");
const readApp=relative=>fs.readFileSync(path.join(appRoot,relative),"utf8");
const readRepo=relative=>fs.readFileSync(path.join(repoRoot,relative),"utf8");
const manifest=JSON.parse(readApp("ui/js/bundle.manifest.json"));
const cssManifest=JSON.parse(readApp("ui/css/bundle.manifest.json"));
const html=readApp("index.html");
const ui=readApp("ui/js/oauth-display.js");
const css=readApp("ui/css/dashboard/oauth-display.css");
const boot=readApp("ui/js/boot.js");
const server=readApp("cmd/dashboard-control-server/http_server.go");
const display=readApp("cmd/dashboard-control-server/oauth_display.go");
const loopback=readApp("cmd/dashboard-control-server/google_oauth_loopback.go");
const oauth=readApp("cmd/dashboard-control-server/google_oauth_cli.go")+readApp("cmd/dashboard-control-server/google_oauth_options.go");
const setup=readApp("bin/setup-vdirsyncer.sh");
const integrations=readRepo("INTEGRATIONS.md");
const security=readRepo("SECURITY.md");

assert.ok(manifest.bundles.app.includes("oauth-display.js"),"dashboard bundle must include the OAuth display controller");
assert.ok(cssManifest.bundles.dashboard.includes("dashboard/oauth-display.css"),"dashboard bundle must include OAuth display styling");
assert.match(html,/<div id="oauthdisplay"[^>]*aria-hidden="true"[^>]*aria-modal="true"/,"kiosk overlay must start hidden and remain an accessible modal shell");
assert.match(html,/id="oauthdisplay-qr"[^>]*hidden/,"QR image must start hidden");
assert.match(boot,/oauthDisplayBoot\(\)/,"dashboard boot must arm the low-frequency overlay poll");
assert.match(ui,/fetch\("\/api\/oauth-display",\{cache:"no-store"\}\)/,"overlay must request only its no-store metadata endpoint");
assert.match(ui,/response\.status===404\)\{ oauthDisplayHide\(\); return; \}/,"overlay must dismiss itself when the presentation is gone");
assert.doesNotMatch(ui,/\.style\.display\s*=/,"overlay visibility must use semantic classes instead of inline display mutation");
assert.match(css,/background:#fff/,"QR must use an always-white backing panel in every dashboard theme");
assert.match(css,/min-width:min\(40vh,70vw\)/,"QR backing panel must stay touch-visible on the kiosk display");
assert.doesNotMatch(server,/GET \/oauth\/google\/callback/,"Dash-Go must not publish a dead advanced OAuth callback route");
assert.match(server,/GET \/api\/oauth-display/,"server must register the loopback display metadata route");
assert.match(server,/HEAD \/api\/oauth-display/,"display routes must retain the API JSON 405 contract for HEAD");
assert.match(server,/requireLoopback\(a\.handleOAuthDisplayMetadata\)/,"kiosk display metadata must remain loopback-only");
assert.match(display,/oauthDisplayTTL\s*=\s*10 \* time\.Minute/,"presentation window must remain bounded to ten minutes");
assert.match(display,/googleOAuthDisplayOnly/,"phone QR paste-back must arm a display-only state");
assert.doesNotMatch(display,/handleGoogleOAuthCallback|paths\.callback|googleOAuthRelayWait/,"display implementation must not retain a public callback spool");
assert.match(loopback,/net\.Listen\("tcp", "127\.0\.0\.1:8433"\)/,"recommended computer flow must bind only a temporary local Desktop-app listener");
assert.match(loopback,/googleOAuthLoopbackWaitWith/,"loopback wait must be directly testable and bounded");
assert.match(oauth,/code_challenge_method/,"authorization must use PKCE S256");
assert.match(oauth,/"loopback"/,"CLI must expose the recommended temporary local callback mode");
assert.match(oauth,/"display-dir"/,"CLI must expose kiosk QR paste-back presentation mode");
assert.doesNotMatch(oauth,/relay-dir|redirect-uri|googleOAuthValidateRelayOptions/,"CLI must not retain an unreachable advanced callback mode");
assert.match(setup,/Choose application type: Desktop app\./,"ordinary Google setup must name the only client type users should choose");
assert.doesNotMatch(setup,/OAuth client type \[desktop\/web/,"ordinary setup must not expose desktop/web architecture jargon");
assert.match(setup,/-loopback/,"ordinary computer setup must invoke the temporary local callback");
assert.match(setup,/-display-dir "\$OAUTH_DISPLAY_DIR"/,"phone fallback must show a kiosk QR without enabling a callback");
assert.match(setup,/PRIVATE_GOOGLE_MODE" = loopback[\s\S]{0,180}oauth_args\+=\(-loopback\)[\s\S]{0,180}else[\s\S]{0,180}-qr -display-dir/,"loopback setup must not also print the phone/paste-back QR");
assert.doesNotMatch(setup,/bullseye-backports|DASH_VDIR_APT_CODENAME/,"unsupported Bullseye backports must not be added by private-calendar setup");
assert.match(setup,/apt_with_lock_wait\s+install\s+-y\s+pipx\s+python3-venv/,"supported private-calendar setup must install pipx and Python venv support through the lock-aware APT wrapper");
assert.match(setup,/apt-get\s+-o\s+"DPkg::Lock::Timeout=\$timeout"/,"the APT wrapper must retain its bounded dpkg-lock wait");
assert.match(setup,/python3 -m pip install --user/,"last-resort user-level pip fallback must remain explicit and non-root");
assert.doesNotMatch(setup,/sudo pip|--break-system-packages/,"private-calendar fallback must never use unsafe system pip mutations");
assert.match(integrations,/temporary SSH bridge/,"integration guidance must describe the recommended automatic computer path");
assert.match(security,/does not expose a public OAuth callback endpoint/i,"security guidance must state the phone paste-back boundary");
console.log("PASS: Google OAuth display stays short-lived and loopback-only, with one Desktop-app path plus a truthful phone paste-back fallback.");
