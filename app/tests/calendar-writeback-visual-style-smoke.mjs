import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {resolve} from "node:path";

const root=resolve(process.argv[2]||".");
const read=rel=>readFileSync(resolve(root,rel),"utf8");
const form=read("ui/js/calendar-event-form.js");
const writeback=read("ui/js/calendar-writeback.js");
const privateCalendars=read("ui/js/control-private-calendars.js");
const dashboardCSS=read("ui/css/dashboard/calendar-writeback.css");
const controlCSS=read("ui/css/control/consistency.css");

assert.match(form,/calendarWritebackCalendarChoices/,'calendar picker must disambiguate duplicate display names without provider IDs');
assert.match(form,/calendar-writeback-calendar-options/,'calendar picker must open an in-form themed option list');
assert.match(form,/calendar-writeback-calendar-fixed/,'fixed ownership must replace a disabled browser select for existing events');
assert.match(form,/aria-controls/,'calendar picker trigger needs an explicit controlled-region relationship');
assert.match(form,/aria-expanded/,'calendar picker trigger must expose whether its choices are visible');
assert.match(form,/calendarWritebackFormTap/,'picker and quick-time controls must use the popup scroll guard');
assert.match(form,/scrollRoot:calendarWritebackPopupScrollRoot/,'form controls must not trigger while the popup scrolls');
assert.match(form,/if\(!selected&&event\)/,'existing events may not fall back to a different writable calendar');
assert.doesNotMatch(form,/aria-haspopup/,'an in-form disclosure must not masquerade as a browser popup menu');
assert.match(form,/aria-pressed/,'calendar picker options must retain native button semantics and expose the selected choice');
assert.doesNotMatch(form,/role","option/,'calendar picker options must keep native button semantics rather than impersonating listbox items');
assert.match(dashboardCSS,/calendar-writeback-calendar-trigger/,'calendar picker trigger needs a themed touch surface');
assert.match(dashboardCSS,/calendar-writeback-calendar-option\.is-selected/,'selected calendars need a visible semantic state');
assert.match(dashboardCSS,/calendar-writeback-calendar-options\[hidden\]/,'closed picker options must not create an extra scroll surface');
assert.match(dashboardCSS,/calendar-writeback-btn:focus-visible/,'event form actions need explicit keyboard focus styling');
assert.match(dashboardCSS,/calendar-writeback-note-title/,'conflict and repair notes need a semantic heading treatment');
assert.match(dashboardCSS,/var\(--danger,var\(--sun\)\)/,'writeback danger styling needs a theme-safe fallback outside Dashboard Control');
assert.match(writeback,/calendarWritebackAttentionNote\("Sync conflict"/,'conflict popup notes must have a clear semantic heading');
assert.match(writeback,/calendarWritebackAttentionNote\("Connection repair"/,'repair popup notes must have a clear semantic heading');
assert.match(privateCalendars,/ctrlPrivateCalendarPresentation/,'private calendar rows must map machine states to one presentation model');
assert.match(privateCalendars,/Sync conflict — choose a version/,'conflict rows need concise human wording');
assert.match(privateCalendars,/Connection repair required/,'repair rows need concise human wording');
assert.match(privateCalendars,/calmanager-conflict-heading/,'conflict recovery needs a visible section heading');
assert.match(privateCalendars,/calmanager-conflict-exit/,'Keep both unchanged needs its own full-width neutral slot');
assert.match(privateCalendars,/"warning"/,'Resolve conflict must use an attention action rather than a positive primary action');
assert.match(controlCSS,/calmanager-state\.healthy/,'healthy calendar rows need a semantic success state');
assert.match(controlCSS,/calmanager-state\.readonly/,'display-only and edits-off rows need a neutral state');
assert.match(controlCSS,/calmanager-state\.attention/,'repair and authorization rows need a warning state');
assert.match(controlCSS,/calmanager-state\.conflict/,'conflict rows need a danger state');
assert.match(controlCSS,/\.cbtn\.warning/,'Calendar Manager needs a distinct review/attention action style');
console.log("calendar writeback visual style smoke: themed picker, semantic states, conflict hierarchy, and touch-safe form polish hold");
