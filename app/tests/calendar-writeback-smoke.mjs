import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {resolve} from "node:path";
const root=resolve(process.argv[2]||".");
const read=rel=>readFileSync(resolve(root,rel),"utf8");
const manifest=read("ui/js/bundle.manifest.json");
const cssManifest=read("ui/css/bundle.manifest.json");
const writeback=read("ui/js/calendar-writeback.js");
const form=read("ui/js/calendar-event-form.js");
const day=read("ui/js/day-popup.js");
const event=read("ui/js/event-popup.js");
const control=read("ui/js/control-calendar-writeback.js");
const cache=read("ui/js/event-cache.js");
const routesPublic=read("cmd/dashboard-control-server/http_routes_public_post.go");
const routesPrivate=read("cmd/dashboard-control-server/http_routes_post_calendar.go");
const core=read("cmd/dashboard-control-server/calendar_writeback.go");
const registry=read("internal/calendar/writeback/registry.go");
const items=read("internal/calendar/writeback/items.go");
const ical=read("internal/calendar/icalwrite/edit.go");
const setup=read("bin/setup-vdirsyncer.sh");
const facade=read("cmd/dashboard-control-server/calendar_facade.go");

assert.match(manifest,/"calendar-writeback\.js"[\s\S]*?"calendar-event-form\.js"/,'writeback UI must be bundled after event popup helpers');
assert.match(cssManifest,/"dashboard\/calendar-writeback\.css"/,'writeback UI needs themed popup styles');
assert.doesNotMatch(writeback,/^\s*calendarWritebackStatus\(\);\s*$/m,'writeback status may not fetch at dashboard boot');
assert.match(day,/calendarWritebackMountDayAdd\(root,day,token\)/,'day popup must lazily expose Add event only when eligible');
assert.match(event,/calendarWritebackEventActions/,'event popup must add only server-declared writeback actions');
assert.match(form,/calendarWritebackActiveCalendars/,'calendar picker must include only writable registry entries');
assert.match(form,/if\(event\)calendar\.disabled=true/,'editing must retain the event in its original remote collection');
assert.match(form,/endDate\.value<=startDate\.value/,'all-day edits must keep an exclusive end date');
assert.match(form,/February 31/,'timed date entry must reject JavaScript date normalization');
assert.match(form,/showOSKFor/,'writeback fields must use the shared OSK');
assert.match(cache,/cache\.version!==7/,'cache must reject pre-writeback capability records');
assert.match(cache,/writeback:/,'last-known event persistence must retain writeback capability');
assert.match(routesPublic,/\/api\/calendar\/event\/create[\s\S]*?calendarWritebackRequirePIN/,'create/edit/skip are public only when writeback does not require PIN');
assert.match(routesPrivate,/\/api\/calendar\/event\/delete/,'delete must remain inside the token-gated calendar route');
assert.match(core,/WithSyncLock/,'mutations must share vdirsyncer\'s lock');
assert.match(core,/queueCalendarWritebackSync/,'remote push must be background-only after a user mutation');
assert.match(core,/Dashboard refresh will retry automatically/,'a locally saved event must not be reported as failed only because the cache refresh failed');
assert.match(registry,/validSource/,'writable sources must be structurally restricted to local calendars/ files');
assert.match(registry,/RegisteredSource/,'Calendar Manager must protect derived mirrors even when edits are disabled');
assert.match(items,/RemoveDurable/,'deleting a vdir item must be durable');
assert.match(ical,/single VEVENT document required/,'aggregate ICS files must not be edited');
assert.match(ical,/TZID=/,'skip must retain the DTSTART timezone form');
assert.match(setup,/Broad discovered mirrors stay read-only/,'broad CalDAV discovery must remain display-only');
assert.match(setup,/exact="\$collection\/\$local_id"/,'setup must register only one exact local vdir collection');
assert.match(setup,/coll_spec=.*remote_id.*local_id/,'selected collections must preserve opaque remote IDs separately from local vdir keys');
assert.doesNotMatch(setup,/conflict_resolution = "a wins"/,'new private calendar pairs must not silently prefer remote conflicts');
assert.match(core,/--pair/,'post-edit writes must target only the affected private calendar pair');
assert.match(facade,/private calendar mirrors cannot be deleted/,'server must reject direct attempts to trash a remote mirror');
assert.doesNotMatch(writeback,/window\.(?:alert|confirm|prompt)\s*\(/,'calendar writeback may not use browser dialogs');
console.log('calendar writeback smoke: opt-in private vdir edits, strict read-only boundaries, safe popup lifecycle, and protected mirrors hold');
