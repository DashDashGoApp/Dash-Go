#!/usr/bin/env node
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import {fileURLToPath} from "node:url";
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),"..");
const read=p=>fs.readFileSync(path.join(root,p),"utf8");
const server=read("cmd/dashboard-control-server/http_server.go");
const policy=read("cmd/dashboard-control-server/request_security.go");
const outbound=read("internal/weather/outbound_security.go");
const privateCalendar=read("tests/private-calendar-controls-smoke.mjs");
const index=read("index.html");
assert.match(server,/os\.OpenRoot\(/,"static serving must use os.Root confinement");
assert.match(server,/http\.ServeContent/,"static serving must serve already-opened files");
assert.doesNotMatch(server,/http\.ServeFile/,"request-derived static paths must not reach ServeFile");
assert.doesNotMatch(server,/func mutableStaticRevision\(path string/,"mutable revision must not accept arbitrary filesystem paths");
assert.match(server,/StatusMisdirectedRequest/,"unapproved Host headers must be rejected");
assert.match(server,/Cross-Origin-Resource-Policy/,"CORP header missing");
assert.match(server,/Content-Security-Policy/,"CSP header missing");
assert.match(policy,/127\.0\.0\.1:/,"IPv4 loopback host allowlist missing");
assert.match(policy,/\[::1\]:/,"IPv6 loopback host allowlist missing");
assert.match(policy,/Retry-After/,"expensive-operation limiter must expose Retry-After");
assert.match(outbound,/DialContext/,"custom Weather transport must validate at connection time");
assert.match(outbound,/127\.0\.0\.0\/8/,"custom Weather transport must reject IPv4 loopback");
assert.match(outbound,/::\/96/,"custom Weather transport must reject IPv6 loopback and IPv4-compatible forms");
assert.match(outbound,/64:ff9b::\/96/,"custom Weather transport must reject well-known NAT64 translation");
assert.match(outbound,/64:ff9b:1::\/48/,"custom Weather transport must reject local-use NAT64 translation");
assert.match(outbound,/2002::\/16/,"custom Weather transport must reject 6to4 translation");
assert.match(outbound,/3fff::\/20/,"custom Weather transport must reject current IPv6 documentation space");
assert.match(outbound,/169\.254\.0\.0\/16/,"custom Weather transport must reject IPv4 link-local targets");
assert.match(outbound,/fe80::\/10/,"custom Weather transport must reject IPv6 link-local targets");
assert.match(outbound,/100\.64\.0\.0\/10/,"custom Weather transport must reject CGNAT targets");
assert.match(outbound,/198\.18\.0\.0\/15/,"custom Weather transport must reject benchmark targets");
assert.match(outbound,/addr = addr\.Unmap\(\)/,"custom Weather transport must classify IPv4-mapped IPv6 consistently");
assert.match(outbound,/redirected to a different host/,"custom Weather redirects must remain on the validated host");
assert.doesNotMatch(privateCalendar,/new RegExp\(endpoint\.replace/,"fixed endpoint literals must not use incomplete regex escaping");
assert.ok(index.includes('/ui/js/preflight-fit.js'),"CSP-compatible external first-paint script missing");
assert.doesNotMatch(index,/<script>\s*\(function/,"dashboard HTML must not retain the inline bootstrap script");
console.log("PASS: beta.3 rooted static serving, DNS-rebinding boundary, CSP/CORP, SSRF controls, and operation limiting are present.");
