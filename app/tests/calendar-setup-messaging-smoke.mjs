import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {resolve} from "node:path";
import {fileURLToPath} from "node:url";
const root=resolve(process.argv[2]||fileURLToPath(new URL("..",import.meta.url)));
const read=rel=>readFileSync(resolve(root,rel),"utf8");
const quick=read("ui/js/control-system-actions.js");
const calendar=read("ui/js/control-calendars-logs.js");
const install=read("../installer/install.sh");
assert.doesNotMatch(quick,/installer option 5/,"Quick Actions must not point at the retired installer option");
assert.match(quick,/option 9 for a read-only calendar link/,"Quick Actions must identify read-only links as option 9");
assert.match(quick,/option 10 for signed-in personal calendar sync/,"Quick Actions must direct signed-in calendar setup to option 10");
assert.doesNotMatch(calendar,/installer option 5/,"Calendar empty state must not point at the retired installer option");
assert.match(calendar,/option 9 for a read-only calendar link/,"Calendar empty state must identify read-only links");
assert.match(calendar,/option 10 for signed-in personal calendar sync/,"Calendar empty state must identify signed-in calendar sync");
assert.match(install,/Read-only calendar link/,"Installer must label option 9 as a read-only calendar link");
assert.match(install,/Personal calendar sync/,"Installer must label option 10 as personal calendar sync");
assert.match(install,/view-only or two-way sync/,"Installer must explain option 10 access modes");
console.log("PASS: calendar messaging distinguishes read-only links from signed-in personal sync and names the correct installer actions.");
